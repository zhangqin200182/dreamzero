def find_checkpoints(root_dir):
    """Find all checkpoint-N directories, return sorted by step number."""
    pattern = re.compile(r'checkpoint-(\d+)$')
    checkpoints = []
    for entry in os.listdir(root_dir):
        m = pattern.match(entry)
        if m:
            step = int(m.group(1))
            path = os.path.join(root_dir, entry)
            adapter = os.path.join(path, "adapter_model.safetensors")
            if os.path.isfile(adapter):
                checkpoints.append((step, path))
    checkpoints.sort(key=lambda x: x[0])
    return checkpoints


def load_model(cfg, ckpt_path):
    """Load model once and reuse across checkpoints (only reload LoRA)."""
    from omegaconf import OmegaConf
    from hydra.utils import instantiate
    from groot.vla.common.utils.device import DEVICE

    model = instantiate(cfg.model)
    model.eval()
    model.to(DEVICE)
    model.post_initialize()
    return model


def load_lora(model, ckpt_path):
    """Load LoRA adapter weights into the model."""
    from safetensors.torch import load_file

    adapter_file = os.path.join(ckpt_path, "adapter_model.safetensors")
    if not os.path.isfile(adapter_file):
        raise FileNotFoundError(f"No adapter_model.safetensors in {ckpt_path}")

    sd = load_file(adapter_file)
    sd = {k.replace(".base_layer.", "."): v for k, v in sd.items()}
    missing, unexpected = model.load_state_dict(sd, strict=False)
    print(f"  Loaded LoRA: {len(sd)} keys, {len(missing)} missing, {len(unexpected)} unexpected")
    return model


def _reset_model_state(ah):
    ah.current_start_frame = 0
    ah.language = None
    ah.clip_feas = None
    ah.ys = None
    ah.kv_cache1 = None
    ah.kv_cache_neg = None
    ah.crossattn_cache = None
    ah.crossattn_cache_neg = None


def prepare_input(sample):
    """Format a dataset sample for lazy_joint_video_action_causal."""
    from groot.vla.common.utils.device import DEVICE
    from groot.vla.model.dreamzero.transform.dreamzero_cotrain import HuggingfaceTokenizer

    tk = HuggingfaceTokenizer(name="/checkpoints/umt5-xxl", seq_len=512, clean='whitespace')
    txt = sample.get("text", "") or ""
    ids, amask = tk([txt], return_mask=True)
    neg_ids, neg_mask = tk([""], return_mask=True)

    inp = {
        "images": sample["images"],
        "state": sample["state"],
        "action": sample["action"],
        "text": ids,
        "text_attention_mask": amask,
        "text_negative": neg_ids,
        "text_attention_mask_negative": neg_mask,
        "embodiment_id": sample["embodiment_id"],
        "has_real_action": sample.get("has_real_action", True),
        "action_mask": sample.get("action_mask", torch.ones(len(sample["action"]), 32)),
    }

    _skip = {"text", "text_attention_mask", "text_negative", "text_attention_mask_negative"}
    for k in list(inp.keys()):
        v = inp[k]
        if isinstance(v, torch.Tensor):
            inp[k] = v.to(DEVICE) if k in _skip else v.unsqueeze(0).to(DEVICE)
        elif isinstance(v, np.ndarray):
            inp[k] = torch.tensor([v.item()], device=DEVICE) if v.ndim == 0 else torch.from_numpy(v).unsqueeze(0).to(DEVICE)
        elif isinstance(v, (int, float, bool, np.integer, np.floating, np.bool_)):
            inp[k] = torch.tensor([int(v) if isinstance(v, (bool, np.bool_)) else v], device=DEVICE)

    ah = model.action_head if 'model' in dir() else None
    # We return inp and let caller handle state truncation with model
    return inp


def run_inference(model, sample, mode="full"):
    """Run inference. mode: 'full' or 'action_only'."""
    from groot.vla.common.utils.device import DEVICE
    from groot.vla.model.dreamzero.transform.dreamzero_cotrain import HuggingfaceTokenizer

    ah = model.action_head
    _reset_model_state(ah)

    tk = HuggingfaceTokenizer(name="/checkpoints/umt5-xxl", seq_len=512, clean='whitespace')
    txt = sample.get("text", "") or ""
    ids, amask = tk([txt], return_mask=True)
    neg_ids, neg_mask = tk([""], return_mask=True)

    inp = {
        "images": sample["images"],
        "state": sample["state"],
        "action": sample["action"],
        "text": ids,
        "text_attention_mask": amask,
        "text_negative": neg_ids,
        "text_attention_mask_negative": neg_mask,
        "embodiment_id": sample["embodiment_id"],
        "has_real_action": sample.get("has_real_action", True),
        "action_mask": sample.get("action_mask", torch.ones(len(sample["action"]), 32)),
    }

    _skip = {"text", "text_attention_mask", "text_negative", "text_attention_mask_negative"}
    for k in list(inp.keys()):
        v = inp[k]
        if isinstance(v, torch.Tensor):
            inp[k] = v.to(DEVICE) if k in _skip else v.unsqueeze(0).to(DEVICE)
        elif isinstance(v, np.ndarray):
            inp[k] = torch.tensor([v.item()], device=DEVICE) if v.ndim == 0 else torch.from_numpy(v).unsqueeze(0).to(DEVICE)
        elif isinstance(v, (int, float, bool, np.integer, np.floating, np.bool_)):
            inp[k] = torch.tensor([int(v) if isinstance(v, (bool, np.bool_)) else v], device=DEVICE)

    if inp["state"].shape[1] > ah.model.num_state_per_block:
        inp["state"] = inp["state"][:, -ah.model.num_state_per_block:]

    saved_decouple = ah.config.decouple_inference_noise
    saved_final_noise = ah.config.video_inference_final_noise

    if mode == "action_only":
        ah.config.decouple_inference_noise = True
        ah.config.video_inference_final_noise = 1.0

    try:
        with torch.no_grad():
            t0 = time.time()
            output = model.lazy_joint_video_action_causal(inp)
            elapsed = time.time() - t0
    finally:
        if mode == "action_only":
            ah.config.decouple_inference_noise = saved_decouple
            ah.config.video_inference_final_noise = saved_final_noise

    return output, elapsed


def compute_mse(gt, pred):
    if gt is None or pred is None:
        return float('inf')
    T = min(len(gt), len(pred))
    return float(np.mean((gt[:T] - pred[:T]) ** 2))


def save_action_plot(gt, pred, path, title):
    T, D = min(len(gt), len(pred)), min(gt.shape[1], pred.shape[1], 7)
    fig, axes = plt.subplots(D, 1, figsize=(10, 2 * D), sharex=True)
    if D == 1:
        axes = [axes]
    for d in range(D):
        axes[d].plot(range(T), gt[:T, d], 'b-', label='GT', lw=2, alpha=.7)
        axes[d].plot(range(T), pred[:T, d], 'r--', label='Pred', lw=2, alpha=.7)
        axes[d].set_ylabel(f"J{d}"); axes[d].legend(fontsize=7); axes[d].grid(alpha=.3)
    axes[-1].set_xlabel("Step")
    plt.suptitle(title); plt.tight_layout()
    plt.savefig(path, dpi=100, bbox_inches='tight'); plt.close()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint_root", required=True,
                        help="Root dir containing checkpoint-N/ subdirs")
    parser.add_argument("--output_root", default="eval",
                        help="Output root directory")
    parser.add_argument("--num_samples", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--steps", type=int, nargs="+", default=None,
                        help="Specific checkpoint steps to eval (default: all)")
    args = parser.parse_args()

    os.makedirs(args.output_root, exist_ok=True)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    # Find checkpoints
    all_ckpts = find_checkpoints(args.checkpoint_root)
    if args.steps:
        all_ckpts = [(s, p) for s, p in all_ckpts if s in args.steps]
    if not all_ckpts:
        print(f"No checkpoints found in {args.checkpoint_root}")
        return

    print(f"Found {len(all_ckpts)} checkpoints: {[s for s, _ in all_ckpts]}")

    # Load config from first checkpoint's parent dir
    from omegaconf import OmegaConf
    first_ckpt_dir = all_ckpts[0][1]
    exp_dir = os.path.dirname(first_ckpt_dir)
    cfg_dir = os.path.join(exp_dir, "experiment_cfg")
    cfg_file = None
    for root, dirs, files in os.walk(cfg_dir):
        for f in files:
            if f in ("conf.yaml", "config.yaml"):
                cfg_file = os.path.join(root, f)
                break
    if cfg_file is None:
        raise FileNotFoundError(f"No config in {cfg_dir}")
    cfg = OmegaConf.load(cfg_file)
    print(f"Loaded config: {cfg_file}")

    # Load model once
    print("Loading base model...")
    model = load_model(cfg, first_ckpt_dir)
    print("Model loaded.")

    # Load fixed samples from dataset
    from hydra.utils import instantiate
    ds = instantiate(cfg.train_dataset)
    np.random.seed(args.seed)
    it = iter(ds)
    samples = [next(it) for _ in range(args.num_samples)]
    print(f"Loaded {len(samples)} fixed evaluation samples")

    all_summaries = []

    for step, ckpt_path in all_ckpts:
        step_str = f"step_{step:04d}"
        out_dir = os.path.join(args.output_root, step_str)
        full_dir = os.path.join(out_dir, "full")
        ao_dir = os.path.join(out_dir, "action_only")
        os.makedirs(full_dir, exist_ok=True)
        os.makedirs(ao_dir, exist_ok=True)

        print(f"\n{'='*60}")
        print(f"Checkpoint step={step}  ({ckpt_path})")

        # Load LoRA for this checkpoint
        try:
            load_lora(model, ckpt_path)
        except Exception as e:
            print(f"  SKIP: Failed to load LoRA: {e}")
            continue

        results = []
        for i, sample in enumerate(samples):
            gt = sample["action"].float().numpy() if hasattr(sample["action"], 'numpy') else np.asarray(sample["action"])
            r = {"episode": i, "gt_action": gt}

            # Full
            try:
                out, t = run_inference(model, sample, mode="full")
                pred = out["action_pred"][0].cpu().float().numpy()
                r["full_pred"] = pred; r["full_time"] = t
                r["full_mse"] = compute_mse(gt, pred)
                save_action_plot(gt, pred, os.path.join(full_dir, f"ep_{i:02d}.png"), f"Full step={step} ep={i}")
                print(f"  Full[{i}]: MSE={r['full_mse']:.4f} t={t:.1f}s")
            except Exception as e:
                import traceback; traceback.print_exc()
                print(f"  Full[{i}] FAILED: {e}")
                r["full_pred"] = None

            # Action-Only
            try:
                out, t = run_inference(model, sample, mode="action_only")
                pred = out["action_pred"][0].cpu().float().numpy()
                r["action_only_pred"] = pred; r["action_only_time"] = t
                r["action_only_mse"] = compute_mse(gt, pred)
                save_action_plot(gt, pred, os.path.join(ao_dir, f"ep_{i:02d}.png"), f"AO step={step} ep={i}")
                print(f"  AO[{i}]:   MSE={r['action_only_mse']:.4f} t={t:.1f}s")
            except Exception as e:
                import traceback; traceback.print_exc()
                print(f"  AO[{i}] FAILED: {e}")
                r["action_only_pred"] = None

            results.append(r)

        # Summary for this checkpoint
        fm = [r["full_mse"] for r in results if r.get("full_mse") is not None and r["full_mse"] != float('inf')]
        am = [r["action_only_mse"] for r in results if r.get("action_only_mse") is not None and r["action_only_mse"] != float('inf')]
        ft = [r["full_time"] for r in results if r.get("full_time") is not None]
        at = [r["action_only_time"] for r in results if r.get("action_only_time") is not None]

        summary = {
            "step": step,
            "checkpoint": ckpt_path,
            "num_samples": len(results),
            "full": {"action_mse_mean": float(np.mean(fm)) if fm else None,
                     "time_mean_sec": float(np.mean(ft)) if ft else None},
            "action_only": {"action_mse_mean": float(np.mean(am)) if am else None,
                            "time_mean_sec": float(np.mean(at)) if at else None},
        }
        with open(os.path.join(out_dir, "summary.json"), "w") as f:
            json.dump(summary, f, indent=2)

        if fm and am:
            delta = (summary["action_only"]["action_mse_mean"] - summary["full"]["action_mse_mean"]) / summary["full"]["action_mse_mean"] * 100
            print(f"  SUMMARY: Full MSE={summary['full']['action_mse_mean']:.4f}, "
                  f"AO MSE={summary['action_only']['action_mse_mean']:.4f}, Δ={delta:+.1f}%")

        all_summaries.append(summary)

    # Write all_summaries.jsonl
    jsonl_path = os.path.join(args.output_root, "all_summaries.jsonl")
    with open(jsonl_path, "w") as f:
        for s in all_summaries:
            f.write(json.dumps(s) + "\n")
    print(f"\nAll summaries: {jsonl_path}")
    print(f"Total checkpoints evaluated: {len(all_summaries)}")


if __name__ == "__main__":
    main()
