#!/usr/bin/env python3
"""
Batch evaluation across all checkpoints.
Runs A/B comparison (Full vs Action-Only) for each checkpoint and saves results.

Usage:
  python scripts/eval/batch_eval.py \
      --checkpoint_root /checkpoints/dreamzero_droid_npu_16gpu_v2 \
      --output_root eval \
      --num_samples 5

Output:
  eval/
    step_0200/
      full/ep_00.png  action_only/ep_00.png  comparison.png  summary.json
    step_0400/...
    trend_mse.png       ← generated by trend_analysis.py
    all_summaries.jsonl
"""
